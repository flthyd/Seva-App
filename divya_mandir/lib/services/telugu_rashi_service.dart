  // Calculate Rashi based on Birth Date (Western / Vedic transit)
  String calculateRashiFromDate(DateTime date) {
    final m = date.month;
    final d = date.day;

    if ((m == 3 && d >= 21) || (m == 4 && d <= 19)) return 'mesha';
    if ((m == 4 && d >= 20) || (m == 5 && d <= 20)) return 'vrushabha';
    if ((m == 5 && d >= 21) || (m == 6 && d <= 20)) return 'mithuna';
    if ((m == 6 && d >= 21) || (m == 7 && d <= 22)) return 'karkataka';
    if ((m == 7 && d >= 23) || (m == 8 && d <= 22)) return 'simha';
    if ((m == 8 && d >= 23) || (m == 9 && d <= 22)) return 'kanya';
    if ((m == 9 && d >= 23) || (m == 10 && d <= 22)) return 'tula';
    if ((m == 10 && d >= 23) || (m == 11 && d <= 21)) return 'vruschika';
    if ((m == 11 && d >= 22) || (m == 12 && d <= 21)) return 'dhanussu';
    if ((m == 12 && d >= 22) || (m == 1 && d <= 19)) return 'makara';
    if ((m == 1 && d >= 20) || (m == 2 && d <= 18)) return 'kumbha';
    return 'meena';
  }
